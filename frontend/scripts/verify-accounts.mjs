import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { parseEnv } from 'node:util';
import { randomUUID, randomBytes } from 'node:crypto';
const require = createRequire(new URL('../../backend/package.json', import.meta.url));
const { Client } = require('pg');
const bcrypt = require('bcryptjs');
const env = parseEnv(await readFile(new URL('../../backend/.env', import.meta.url), 'utf8'));
const db = new Client({ connectionString: env.DATABASE_URL });
await db.connect();
const base = process.env.UI_URL || 'http://127.0.0.1:5173';
const prefix = 'account_ui_' + randomBytes(5).toString('hex');
const password = randomBytes(18).toString('hex');
const temporary = randomBytes(18).toString('hex');
const personal = randomBytes(18).toString('hex');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await mkdir('artifacts', { recursive: true });
async function login(target, username, pass) {
  await target.goto(base);
  await target.getByLabel('Username', { exact: true }).fill(username);
  await target.getByLabel('Password', { exact: true }).fill(pass);
  await target.getByRole('button', { name: 'Sign in', exact: true }).click();
}
async function fits(target) { assert.ok(await target.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No page overflow'); }
try {
  const hash = await bcrypt.hash(password, 4);
  await db.query('INSERT INTO users(id,username,full_name,role,password_hash) VALUES($1,$2,$3,$4,$5)', [randomUUID(), prefix+'_admin', 'Account Verification Admin', 'ADMIN', hash]);
  await login(page, prefix+'_admin', password);
  await page.getByRole('navigation').getByRole('link', { name: 'Account management', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Account management', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Username', { exact: true }).fill(prefix+'_guard');
  await dialog.getByLabel('Full name', { exact: true }).fill('Account Verification Guard');
  await dialog.getByLabel('Temporary password', { exact: true }).fill(temporary);
  await dialog.getByLabel('Confirm temporary password', { exact: true }).fill(temporary);
  await dialog.getByLabel('Your administrator password', { exact: true }).fill(password);
  await dialog.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('searchbox', { name: 'Search accounts' }).fill(prefix+'_guard');
  await expect(page.locator('.accounts-table tbody tr')).toHaveCount(1);
  const stored = (await db.query('SELECT * FROM users WHERE username=$1', [prefix+'_guard'])).rows[0];
  assert.ok(stored.must_change_password && await bcrypt.compare(temporary, stored.password_hash));
  await page.screenshot({ path: 'artifacts/accounts-desktop.png', fullPage: true });
  for (const width of [390,768]) {
    await page.setViewportSize({ width, height: 844 }); await fits(page);
    await page.screenshot({ path: 'artifacts/accounts-'+width+'.png', fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Edit '+prefix+'_guard', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Full name', { exact: true }).fill('Updated Verification Guard');
  await dialog.getByLabel('Your administrator password', { exact: true }).fill(password);
  await page.setViewportSize({ width: 390, height: 844 }); await fits(page);
  await page.screenshot({ path: 'artifacts/accounts-dialog-mobile.png', fullPage: true });
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByText('Updated Verification Guard', { exact: true })).toBeVisible();
  const staffContext = await browser.newContext();
  const staff = await staffContext.newPage();
  staff.on('pageerror', (error) => errors.push(error.message));
  await login(staff, prefix+'_guard', temporary);
  await expect(staff.getByRole('heading', { name: 'Set your password', exact: true })).toBeVisible();
  assert.equal(await staff.getByRole('navigation').count(), 0);
  await staff.getByLabel('Temporary password', { exact: true }).fill(temporary);
  await staff.getByLabel('New password (12+ characters)', { exact: true }).fill(personal);
  await staff.getByLabel('Confirm new password', { exact: true }).fill(personal);
  await staff.getByRole('button', { name: 'Change password and sign out', exact: true }).click();
  await expect(staff.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible();
  await login(staff, prefix+'_guard', personal);
  await expect(staff.getByRole('heading', { name: 'Guard post', exact: true })).toBeVisible();
  assert.equal(await staff.getByRole('link', { name: 'Account management', exact: true }).count(), 0);
  assert.equal((await staffContext.request.get(base+'/api/users')).status(), 403);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  await page.getByRole('navigation').getByRole('link', { name: 'Account management', exact: true }).click();
  await page.getByRole('searchbox', { name: 'Search accounts' }).fill(prefix+'_guard');
  const revoke = page.getByRole('button', { name: 'Revoke sessions for '+prefix+'_guard', exact: true });
  await expect(revoke).toBeEnabled(); await revoke.click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Your administrator password', { exact: true }).fill(password);
  await dialog.getByRole('button', { name: 'Revoke sessions', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  assert.equal((await staffContext.request.get(base+'/api/auth/me')).status(), 401);
  await staffContext.close();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).click();
  await expect(page.locator('.accounts-table tbody tr')).toHaveCount(1);
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.accounts-toolbar select')).backgroundColor === 'rgb(35, 40, 43)');
  await page.screenshot({ path: 'artifacts/accounts-dark.png', fullPage: true });
  for (let i = 0; i < 26; i++) await db.query('INSERT INTO users(id,username,full_name,role,password_hash) VALUES($1,$2,$3,$4,$5)', [randomUUID(), prefix+'_page_'+i, 'Pagination Verification '+i, 'GUARD', hash]);
  await page.route('**/api/users?*', async (route) => { await new Promise((resolve) => setTimeout(resolve, 700)); await route.continue(); });
  await page.getByRole('searchbox', { name: 'Search accounts' }).fill(prefix+'_page_');
  await expect(page.getByRole('status', { name: 'Retrieving accounts' })).toBeVisible();
  await expect(page.locator('.accounts-table tbody tr')).toHaveCount(25);
  await page.unroute('**/api/users?*');
  await page.getByRole('button', { name: 'Next account page', exact: true }).click();
  await expect(page.locator('.accounts-table tbody tr')).toHaveCount(1);
  await expect(page.getByText('Page 2 of 2', { exact: true })).toBeVisible();
  await page.route('**/api/users?*', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ success: false, message: 'Database is unavailable. Please try again.', error: { code: 'DATABASE_UNAVAILABLE' } }) }));
  await page.getByRole('button', { name: 'Refresh accounts', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Showing previously retrieved records.');
  await expect(page.locator('.accounts-table tbody tr')).toHaveCount(1);
  await page.unroute('**/api/users?*');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
  assert.deepEqual(errors, []);
  console.log('PASS: real account creation/edit, forced password replacement, guard restrictions, session revocation, responsive layouts, pagination and loading/error/retry.');
} catch (error) {
  await page.screenshot({ path: 'artifacts/accounts-failure.png', fullPage: true }).catch(() => {});
  console.error('Account screen:', page.url(), 'Feedback:', await page.locator('.resource-feedback').innerText().catch(() => 'unavailable'));
  throw error;
} finally {
  await browser.close();
  // Only remove fixtures owned by this run; never touch initial staff accounts.
  const ids = (await db.query('SELECT id FROM users WHERE starts_with(username,$1)', [prefix])).rows.map((row) => row.id);
  await db.query('DELETE FROM audit_logs WHERE actor_id=ANY($1::uuid[]) OR target_id=ANY($1::text[])', [ids]);
  await db.query('DELETE FROM sessions WHERE user_id=ANY($1::uuid[])', [ids]);
  await db.query('DELETE FROM users WHERE id=ANY($1::uuid[])', [ids]);
  await db.end();
}
